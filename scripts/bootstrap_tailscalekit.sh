#!/usr/bin/env bash
# Build official TailscaleKit (latest libtailscale) and wire it into Codeg iOS.
# macOS + Xcode + Go required. Run from the repo root, then `xcodegen generate`.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
VENDOR="$ROOT/Vendor"
SRC="$VENDOR/libtailscale"
OUT="$VENDOR/TailscaleKit"
REPO="https://github.com/tailscale/libtailscale.git"

if ! command -v go >/dev/null 2>&1; then
  echo "Go is required to build TailscaleKit. Install the current Go release." >&2
  exit 1
fi
if ! command -v xcodebuild >/dev/null 2>&1; then
  echo "Xcode is required to build TailscaleKit." >&2
  exit 1
fi

mkdir -p "$VENDOR"
if [[ -d "$SRC/.git" ]]; then
  git -C "$SRC" fetch --depth 1 origin main
  git -C "$SRC" checkout --force FETCH_HEAD
else
  git clone --depth 1 --branch main "$REPO" "$SRC"
fi

SHA="$(git -C "$SRC" rev-parse HEAD)"
echo "Building TailscaleKit from libtailscale $SHA"

make -C "$SRC/swift" ios-fat

mkdir -p "$OUT"
# The fat xcframework lands under swift/build; copy whatever make produced.
FOUND="$(find "$SRC/swift" -name 'TailscaleKit.xcframework' -type d | head -n 1)"
if [[ -z "$FOUND" ]]; then
  echo "make ios-fat did not produce TailscaleKit.xcframework" >&2
  exit 1
fi
rm -rf "$OUT/TailscaleKit.xcframework"
cp -R "$FOUND" "$OUT/TailscaleKit.xcframework"
printf '%s\n' "$SHA" > "$OUT/VERSION"

cat > "$ROOT/project.tailscale.yml" <<EOF
# Generated by scripts/bootstrap_tailscalekit.sh — do not hand-edit.
# libtailscale $SHA
targets:
  CodegiOS:
    dependencies:
      - framework: Vendor/TailscaleKit/TailscaleKit.xcframework
        embed: true
        codeSign: true
    settings:
      base:
        OTHER_SWIFT_FLAGS: "\$(inherited) -D CODEG_TAILSCALEKIT"
EOF

echo "TailscaleKit ready. Run: xcodegen generate"
